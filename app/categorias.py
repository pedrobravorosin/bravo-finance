def normaliza(desc):
    return re.sub(r"\s+", " ", desc.upper()).strip()


def categoria(desc, overrides):
    k = normaliza(desc)
    if k in overrides:
        return overrides[k]
    for nome, pad in REGRAS:
        if re.search(pad, k):
            return nome
    return "Outros"
